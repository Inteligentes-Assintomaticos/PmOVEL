// Console.log
// Esse comando é utilizado para imprimir mensagens no console do navegador. Ele é muito útil para depuração e para verificar o valor de variáveis durante a execução do código.

console.log("Olá, mundo!"); // Imprime "Olá, mundo!" no console

//Alert
// O comando alert é utilizado para exibir uma caixa de diálogo com uma mensagem para o usuário. Ele é útil para chamar a atenção do usuário ou para fornecer informações importantes.

alert("Bem-vindo ao curso de JavaScript!"); // Exibe um alerta com a mensagem "Bem-vindo ao curso de JavaScript!"





